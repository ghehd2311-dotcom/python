# 놀이동산 입장료 계산
#  13세 미만: 5000원
#  13세 이상: 10000원

# 실행순서
# 프로그램 시작
#     ↓
# 나이 = 10 → 13세 미만 → 5000원 출력
#     ↓
# 나이 = 20 → 13세 이상 → 10000원 출력
#     ↓
# 나이 = 8  → 13세 미만 → 5000원 출력
#     ↓
# 프로그램 종료

# 나이비교하는 반복되는 코드를 함수로 바꾸기!
def 입장료계산(나이):
    if 나이 < 13:
        print("5000원")
    else:
        print("10000원")

나이 = 10

if 나이 < 13:
    print("5000원")
else:
    print("10000원")


나이 = 20

if 나이 < 13:
    print("5000원")
else:
    print("10000원")


나이 = 8

if 나이 < 13:
    print("5000원")
else:
    print("10000원")