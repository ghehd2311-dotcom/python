# 하나만 콕 집어서 결과(딕셔너리)

학생들 = {
    "김민수" : "010-1234-1234",
    "이진연" : "010-1234-2580",
    "유재석" : "010-2580-2580"
}
# 김민수가 내 연락처에 있는지 확인
검색할이름 = "김민수"

# 딕셔너리 key를 기준으로 검색한다!
결과 = 검색할이름 in 학생들

# 딕셔너리를 하나씩 꺼내서 출력하는 문장!
# 자동으로 데이터를 꺼내서 print()
for 학생한명 in 학생들:
    print(학생한명)
    print(학생들[학생한명])

# 딕셔너리도 key랑 value을 한꺼번에 뽑아주는
# 기능 items()

for key,value in 학생들.items():
    print("key:", key)
    print("value: ", value)

