# 장바구니에 담긴 내용들을 출력하는 프로그램
장바구니목록 = [
    {
        "상품명" : "짬뽕",
        "가격" : 15000,
        "수량" : 10
    },
    {
        "상품명" : "생수",
        "가격" : 8000,
        "수량" : 2
    },
    {
        "상품명" : "초코바",
        "가격" : 9000,
        "수량" : 3
    }
]

합 = 0;
for 바구니 in 장바구니목록:
    합 += 바구니["가격"] * 바구니["수량"]
    
print("장바구니 총합:", 합)
