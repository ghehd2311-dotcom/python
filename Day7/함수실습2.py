# 춘천, 부산, 대구, 수원으로 가는
# 기차표를 예매하는 프로그램을 작성하려 한다.
# 각 도시 당 5,000원, 30,000원, 20,000원,
# 10,000원의 비용이 든다. 도시 이름을 입력하면
# 금액을 결정하고 출력해주는 함수를 작성해보시오.

def 운임비(목적지):
    if 목적지 == "춘천":
        print("5,000원")
    elif 목적지 == "부산":
        print("30,000원")
    elif 목적지 == "대구":
        print("20,000원")
    elif 목적지 == "수원":
        print("10,000원")
    else:
        print("잘못된 도시입니다.")

운임비("춘천")