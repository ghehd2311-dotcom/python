# 친구 이름 찾기
# 1. 저장할 데이터?
# 2. 실행 순서?


친구목록 = ["민수","지영","철수"]

# 1. 친구 목록을 전체 출력
st.write(친구목록)
# 2. 몇번째 친구 입력할지? number_input()
번호 = st.number_input("몇 번째 친구 인가요?",value=0, min_value=1)

# 3. 선택한 친구의 이름을 출력하시오!
#    없는 친구 "그 번호의 친구는 없어요!"

try:
    친구 = 친구목록[번호]
except:
    st.warning("그 친구번호는 없어요!")
else:
    st.write("선택한 친구: ",친구)