# 주문 평균 금액
# 오늘 하루의 주문 평균을 계산해서 화면에 보여주는 간단한 코드
# value 설정은 기본값 설정
st.subheader("주문 평균 금액")

try:
    총합 = st.number_input("총 매출:",value=1000000)
    주문건수 = st.number_input("주문 건수: ", value=10)
    st.write("평균:", 총합 / 주문건수 , "원")
except ZeroDivisionError as e:
    print("개발자 확인용: ",e)
    st.write("오늘은 주문이 없어요!")

