# 1. 준비
import sqlite3 as db
import streamlit as st

# 2. 데이터 저장
#  - 민지가 제목에 오늘 점심, 내용 김치볶음밥을 먹었어요 등록!눌렀어요
#  - 내일 프로그램 다시 열었을때 이 글이 보여야된다.

# 한줄에 무엇을 기록할까?
# 한줄 = 한 사람이 등록한 게시글 하나

# 누가 작성했는지?  민지          작성자
# 어떤 내용?  김치볶음밥먹음       내용
# 어떤 제목?     오늘 점심        제목
# 언제 작성?     현재 시간        작성시간
# 게시글을 순서대로 저장하기 위해서 글의 번호를 저장한다.

# 3. 저장소 만들기
con = db.connect("posts.db")

#  -2) 저장소를 조작할 수있는 커서
db조작 = con.cursor()

# 4. 어떤 내용들이 저장될지 테이블(표형식)정의
db조작.execute("""
    CREATE TABLE IF NOT EXISTS posts(
        글번호 INTEGER PRIMARY KEY AUTOINCREMENT,
        작성자 TEXT,
        제목 TEXT,
        내용 TEXT
    )
""")

#5. 화면
st.title("우리 반 게시판")
작성자 = st.selectbox("누구의 화면인가요?", ["민지", "준호"])
제목 = st.text_input("제목").strip()
내용 = st.text_area("내용").strip()

if st.button("게시글 등록"):
    # 제목과 내용에 공백이 있으면 제목과 내용 둘중 하나 공백
    if 제목 == "" or 내용 == "":
        st.warning("제목과 내용 확인해주세요!")
    else:
        # 게시글 추가하기
        # 명령어! (insert into)
        db조작.execute(f"""
            insert into
                posts (작성자,제목,내용)
            values
                ('{작성자}','{제목}','{내용}')
        """)

        con.commit()
        st.success(" 게시글이 등록 되었습니다!")

# 전체 게시글 불러오기
st.subheader("전체 게시글")

# 커서한테 부탁한다(조회)

# 추가 insert into
# 조회 select

db조작.execute("""
    select   -- 2) 조회(출력)
        *
    from     -- 1)테이블
        posts
""")

# 위에 명령문이 실행하면 db조작(커서)가 데이터를 전부 가지고 있다.
# 파이썬으로 전부 꺼내기!
게시글목록 = db조작.fetchall()

# st.write(게시글목록)

# 자동으로 숫자가 증가하도록 만드는 명령어
# autoincrement
# 1부터 자동으로 데이터가 들어오면 하나씩 증가하면서
# 저장한다.
# 다른 데이터베이스를 사용할 때 확인!

# for post in 게시글목록:
#     st.write(post)
for 글번호,작성자,제목,내용 in 게시글목록:
    st.write(글번호,작성자,제목,내용)