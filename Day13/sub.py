import streamlit as st
import pandas as pd

# 머신러닝 도구 모델을 가져오는 import
from sklearn.linear_model import LinearRegression

st.title("오차")

# 오차 MAE , MSE 구글 검색!
#  모델 비교해서 누가 더 정확한가?숫자로 말한다
# 오차 = 실제 - 예상
# 차이: 내 예상과 실제가 얼마나 다르냐?

#  평균 몇 분 틀렸나를 숫자로 답하는것을 MAE

st.header("친구가 도착 시간: 평균 몇분 틀렸나 MAE)")

# 실제 걸린 시간 입력!
월 = st.number_input("월요일 걸린시간:(분)",value=10,min_value=0)
화 = st.number_input("화요일 걸린시간:(분)",value=10,min_value=0)

# 표로 만든다
표 = pd.DataFrame({
    "요일": ["월요일", "화요일"],
    "내 예상": [10, 10],
    "실제 걸린 시간": [월, 화]
})

# 차이 = 실제 - 예상(많이 걸리면 + , 적게 걸리면 -)
표["차이"] = 표["실제 걸린 시간"] - 표["내 예상"]

# 차이의 크기만 본다(마이너스 없앰)
표["차이 크기"] = 표["차이"].abs()

# 표를 보여준다.
st.write(표)

# MAE = 차이 크기의 평균
mae = 표["차이 크기"].mean()

st.write("MAE 평균적으로 틀린시간:", f"{mae:.1f}분")

# 상황
#  - 배달앱이 4일 연속 30분 걸려요!
#  - 실제 도착은 33,28,34,27분

표 = pd.DataFrame({
    "날짜": ["1일", "2일", "3일", "4일"],
    "앱 예상": [30, 30, 30, 30],
    "실제 도착": [33, 28, 34, 27]
})

# 차이 = 실제 - 예상
표["차이"] = 표["실제 도착"] - 표["앱 예상"]

# 차이 크기
표["차이 크기"] = 표["차이"].abs()

st.write(표)

mae = 표["차이 크기"].mean()
st.write("MAE 평균적으로 틀린시간:", f"{mae:.1f}분")

# MAE 를 하는 이유?
