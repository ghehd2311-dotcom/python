import streamlit as st

# 기준선
st.title("기준선 = 평균만 찍는다")

정답 = [2000, 4000, 6000, 8000, 10000]
평균 = sum(정답) / len(정답)  # 기준선 = 정답의평균
#[평균]  # [6000] *5 -> 리스트 복사 [6000,6000,6000,6000,6000]

# 기준선
# 평균 하나를 정답 개수만큼 복사해서 직선으로 만든다.
기준선 = [평균] * len(정답)

st.line_chart({
    "정답" : 정답,
    "기준선(평균)" : 기준선
})

st.write(f"기준선: {평균:,.0f}원")