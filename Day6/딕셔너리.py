# 딕셔너리.py
# - 데이터를 이름과 값을 연결하는 구조!
# - 사전
# - { key : value }
# key : 데이터를 찾기 위한 이름
# value: 실제 저장 되는 값
# ex) 연락처
#  이서희 - 010-1234-1234

커피메뉴 = {
    "아메리카노" : 2500,
    "수박주스" : 5000,
    "카페라떼" : 3000
}

# 딕셔너리명[key] -> value을 준다.
print(커피메뉴["아메리카노"])


개인정보 = {
    "이름": "이서희",
    "나이": 20,
    "사는곳" : "동탄"
}
# 개인정보 변수에서 이름을 출력!
# 이서희
print(개인정보["이름"])
