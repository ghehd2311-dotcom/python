# friendshipPredict.py

from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error

# ----------------------------------------
# 1. 학습 데이터
# ----------------------------------------

# 힌트(X)
# [대화 시간, 공통 관심사, 흡연 여부, 개인 만남 횟수]
# Yes = 1, No = 0
# 흡연 여부는 가상 상대방의 조건

힌트 = [
    [10, 0, 0, 0],
    [30, 1, 0, 0],
    [20, 0, 1, 1],
    [45, 1, 1, 1],
]

# 정답(y) = 친밀도 점수
# 조원 4명이 각각 평가한 점수
# 현재는 예시 데이터이므로 실제 점수로 변경

조원별정답 = {
    "A": [15, 40, 23, 48],
    "B": [12, 34, 17, 40],
    "C": [20, 50, 28, 61],
    "D": [16, 43, 18, 44]
}

# ----------------------------------------
# 2. 모델 학습 및 평가
# ----------------------------------------

모델들 = {}

for 이름, 친밀도 in 조원별정답.items():

    print(f"\n===== 조원 {이름} =====")

    train = 2
    # 베이스라인
    평균 = sum(친밀도[:train]) / train
    기준선예측 = [평균] * len(친밀도[train:])

    기준오차 = mean_absolute_error(
        친밀도[train:], 기준선예측
    )

    

    print("베이스라인 평균 오차:", round(기준오차, 1))

    # 선형회귀 모델 학습
    모델 = LinearRegression()
    모델.fit(힌트[:train], 친밀도[:train])

    # 뒤의 2개 데이터로 시험
    예측 = 모델.predict(힌트[train:])

    print("정답:", 친밀도[train:])

    for 정답, 답 in zip(친밀도[train:], 예측):
        print(f"정답: {정답}점 / 예측: {답:.1f}점")

    # 평균 오차
    오차 = mean_absolute_error(친밀도[train:], 예측)

    print("평균 오차:", round(오차, 1))
    print("coef_:", 모델.coef_.round(2))
    print("절편:", round(모델.intercept_, 2))

    # 학습한 모델 저장
    모델들[이름] = 모델


# ----------------------------------------
# 3. 새로운 사람의 조건 입력
# ----------------------------------------

# 각 조원과의 관계를 입력
# [대화 시간, 공통 관심사, 흡연 여부, 개인 만남 횟수]

새로운조건 = {
    "A": [60, 1, 0, 2],
    "B": [30, 0, 0, 1],
    "C": [90, 1, 0, 3],
    "D": [45, 1, 0, 1]
}

print("\n===== 친밀도 예측 결과 =====")

for 이름, 입력 in 새로운조건.items():

    모델 = 모델들[이름]

    예측 = 모델.predict([입력])[0]

    print(f"조원 {이름}: {예측:.1f}점")